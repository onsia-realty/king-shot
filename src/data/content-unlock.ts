/** 왕국 원래 시작일(일수). 표 범위 밖이면 null. */
export function kingdomStartDay(kingdom: number): number | null {
  if (!Number.isInteger(kingdom) || kingdom < 1 || kingdom > KINGDOM_MAX) return null;
  // ponytail: 689행 선형 탐색. 입력 한 번에 한 번 도는 거라 이분 탐색까지 필요 없다.
  let offset = KINGDOM_RANGES[0][1];
  for (const [start, days] of KINGDOM_RANGES) {
    if (start > kingdom) break;
    offset = days;
  }
  return START_EPOCH_DAY + offset;
}

